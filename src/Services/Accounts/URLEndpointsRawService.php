<?php

declare(strict_types=1);

namespace Imagekit\Services\Accounts;

use Imagekit\Accounts\URLEndpoints\URLEndpointCreateParams;
use Imagekit\Accounts\URLEndpoints\URLEndpointResponse;
use Imagekit\Accounts\URLEndpoints\URLEndpointUpdateParams;
use Imagekit\Client;
use Imagekit\Core\Contracts\BaseResponse;
use Imagekit\Core\Conversion\ListOf;
use Imagekit\Core\Exceptions\APIException;
use Imagekit\RequestOptions;
use Imagekit\ServiceContracts\Accounts\URLEndpointsRawContract;

final class URLEndpointsRawService implements URLEndpointsRawContract
{
    // @phpstan-ignore-next-line
    /**
     * @internal
     */
    public function __construct(private Client $client) {}

    /**
     * @api
     *
     * **Note:** This API is currently in beta.
     * Creates a new URL‑endpoint and returns the resulting object.
     *
     * @param array{
     *   description: string,
     *   origins?: list<string>,
     *   urlPrefix?: string,
     *   urlRewriter?: array<string,mixed>,
     * }|URLEndpointCreateParams $params
     *
     * @return BaseResponse<URLEndpointResponse>
     *
     * @throws APIException
     */
    public function create(
        array|URLEndpointCreateParams $params,
        ?RequestOptions $requestOptions = null,
    ): BaseResponse {
        [$parsed, $options] = URLEndpointCreateParams::parseRequest(
            $params,
            $requestOptions,
        );

        // @phpstan-ignore-next-line return.type
        return $this->client->request(
            method: 'post',
            path: 'v1/accounts/url-endpoints',
            body: (object) $parsed,
            options: $options,
            convert: URLEndpointResponse::class,
        );
    }

    /**
     * @api
     *
     * **Note:** This API is currently in beta.
     * Updates the URL‑endpoint identified by `id` and returns the updated object.
     *
     * @param string $id Unique identifier for the URL-endpoint. This is generated by ImageKit when you create a new URL-endpoint. For the default URL-endpoint, this is always `default`.
     * @param array{
     *   description: string,
     *   origins?: list<string>,
     *   urlPrefix?: string,
     *   urlRewriter?: array<string,mixed>,
     * }|URLEndpointUpdateParams $params
     *
     * @return BaseResponse<URLEndpointResponse>
     *
     * @throws APIException
     */
    public function update(
        string $id,
        array|URLEndpointUpdateParams $params,
        ?RequestOptions $requestOptions = null,
    ): BaseResponse {
        [$parsed, $options] = URLEndpointUpdateParams::parseRequest(
            $params,
            $requestOptions,
        );

        // @phpstan-ignore-next-line return.type
        return $this->client->request(
            method: 'put',
            path: ['v1/accounts/url-endpoints/%1$s', $id],
            body: (object) $parsed,
            options: $options,
            convert: URLEndpointResponse::class,
        );
    }

    /**
     * @api
     *
     * **Note:** This API is currently in beta.
     * Returns an array of all URL‑endpoints configured including the default URL-endpoint generated by ImageKit during account creation.
     *
     * @return BaseResponse<list<URLEndpointResponse>>
     *
     * @throws APIException
     */
    public function list(?RequestOptions $requestOptions = null): BaseResponse
    {
        // @phpstan-ignore-next-line return.type
        return $this->client->request(
            method: 'get',
            path: 'v1/accounts/url-endpoints',
            options: $requestOptions,
            convert: new ListOf(URLEndpointResponse::class),
        );
    }

    /**
     * @api
     *
     * **Note:** This API is currently in beta.
     * Deletes the URL‑endpoint identified by `id`. You cannot delete the default URL‑endpoint created by ImageKit during account creation.
     *
     * @param string $id Unique identifier for the URL-endpoint. This is generated by ImageKit when you create a new URL-endpoint. For the default URL-endpoint, this is always `default`.
     *
     * @return BaseResponse<mixed>
     *
     * @throws APIException
     */
    public function delete(
        string $id,
        ?RequestOptions $requestOptions = null
    ): BaseResponse {
        // @phpstan-ignore-next-line return.type
        return $this->client->request(
            method: 'delete',
            path: ['v1/accounts/url-endpoints/%1$s', $id],
            options: $requestOptions,
            convert: null,
        );
    }

    /**
     * @api
     *
     * **Note:** This API is currently in beta.
     * Retrieves the URL‑endpoint identified by `id`.
     *
     * @param string $id Unique identifier for the URL-endpoint. This is generated by ImageKit when you create a new URL-endpoint. For the default URL-endpoint, this is always `default`.
     *
     * @return BaseResponse<URLEndpointResponse>
     *
     * @throws APIException
     */
    public function get(
        string $id,
        ?RequestOptions $requestOptions = null
    ): BaseResponse {
        // @phpstan-ignore-next-line return.type
        return $this->client->request(
            method: 'get',
            path: ['v1/accounts/url-endpoints/%1$s', $id],
            options: $requestOptions,
            convert: URLEndpointResponse::class,
        );
    }
}
